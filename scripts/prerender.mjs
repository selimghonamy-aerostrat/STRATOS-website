// Pre-render every page so the browser can paint it before React arrives.
//
// Each *.dc.html page is drawn in the browser by js/support.js, which hides the
// <x-dc> template until React has downloaded from unpkg (about 1 s on phones).
// This script opens each page in headless Chrome, takes the finished HTML and
// styles, and saves them in the page between the PRERENDER markers. The browser
// shows that copy at once; as soon as the runtime has drawn the live page, the
// small inline script removes the copy in the same frame, so nothing flickers.
// The template, the runtime and window.__resources are left untouched.
//
// RE-RUN AFTER EVERY CONTENT OR DESIGN CHANGE, or the old copy shows for ~1 s:
//   cd scripts && npm install && npm run prerender
//
// Needs Google Chrome installed (CHROME_PATH overrides the default macOS path).

import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHROME = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const START = '<!-- PRERENDER:START (generated by scripts/prerender.mjs, do not edit) -->';
const END = '<!-- PRERENDER:END -->';
const BLOCK_RE = /<!-- PRERENDER:START[\s\S]*?<!-- PRERENDER:END -->\n/;

const pages = fs.readdirSync(ROOT).filter((f) => f.endsWith('.dc.html')).sort();
const strip = (src) => src.replace(BLOCK_RE, '');

// Serve the site with the old pre-rendered block removed, so the snapshot always
// comes from the template alone.
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml',
  '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.woff2': 'font/woff2', '.mp4': 'video/mp4' };
const server = http.createServer((req, res) => {
  const p = path.join(ROOT, decodeURIComponent(new URL(req.url, 'http://x').pathname));
  if (!p.startsWith(ROOT) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { res.writeHead(404); return res.end(); }
  let body = fs.readFileSync(p);
  if (p.endsWith('.dc.html')) body = strip(body.toString());
  res.writeHead(200, { 'Content-Type': TYPES[path.extname(p)] || 'application/octet-stream' });
  res.end(body);
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${server.address().port}`;

const browser = await puppeteer.launch({ executablePath: CHROME, headless: true });
let failed = false;
for (const file of pages) {
  const page = await browser.newPage();
  await page.setViewport({ width: 1440, height: 900 });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(`${base}/${file}`, { waitUntil: 'networkidle0', timeout: 60000 });
  await page.waitForSelector('#dc-root > *', { timeout: 30000 });
  await new Promise((r) => setTimeout(r, 1500));

  const snap = await page.evaluate(() => {
    // Styles the runtime added to <head> (page styles, atomics, hover rules)
    const support = document.querySelector('script[src$="support.js"]');
    const css = [];
    let after = false;
    for (const el of document.head.children) {
      if (el === support) { after = true; continue; }
      if (!after || el.tagName !== 'STYLE') continue;
      let text = '';
      try { text = [...el.sheet.cssRules].map((r) => r.cssText).join('\n'); } catch { text = el.textContent; }
      if (/^x-dc\s*\{/.test(text.trim())) continue;
      text = text.replace(/#dc-root/g, '#dc-prerender');
      if (text.trim()) css.push(text);
    }
    const root = document.getElementById('dc-root').cloneNode(true);
    root.querySelectorAll('script').forEach((s) => s.remove());
    root.querySelectorAll('[data-dc-tpl],[data-hidden],[data-observed],[data-rev-idx]').forEach((el) => {
      el.removeAttribute('data-dc-tpl'); el.removeAttribute('data-hidden');
      el.removeAttribute('data-observed'); el.removeAttribute('data-rev-idx');
    });
    // The scroll airplane starts at the left edge; the live page moves it
    root.querySelectorAll('.aerostrat-runway .ship,.aerostrat-runway .laid,.aerostrat-runway .wake').forEach((el) => el.removeAttribute('style'));
    // Reveal-animation helpers the live page adds itself; dropping them keeps runs identical
    root.querySelectorAll('.aerostrat-pop').forEach((el) => {
      el.classList.remove('aerostrat-pop'); if (!el.classList.length) el.removeAttribute('class');
      el.style.removeProperty('transition-delay'); if (!el.getAttribute('style')) el.removeAttribute('style');
    });
    return { css: css.join('\n'), html: root.innerHTML };
  });
  if (errors.length || !snap.html || /<\/?x-dc/.test(snap.html)) {
    console.error(`✗ ${file}: ${errors.join(' | ') || 'empty or invalid snapshot'}`);
    failed = true; await page.close(); continue;
  }

  const handoff = `<script>(function(){var d=document,p=d.getElementById('dc-prerender');if(!p)return;d.documentElement.classList.add('dc-pre');` +
    `var o=new MutationObserver(function(){var r=d.getElementById('dc-root');if(r&&r.firstElementChild){o.disconnect();p.remove();}});` +
    `o.observe(d.body,{childList:true,subtree:true});})();</script>`;
  const block = `${START}\n<div id="dc-prerender"><style>${snap.css}\n#dc-prerender,#dc-prerender>.sc-host{height:100%}</style>` +
    `${snap.html}</div>\n${handoff}\n${END}\n`;

  const src = strip(fs.readFileSync(path.join(ROOT, file), 'utf8'));
  const at = src.indexOf('<x-dc>');
  if (at < 0) throw new Error(`${file}: no <x-dc>`);
  fs.writeFileSync(path.join(ROOT, file), src.slice(0, at) + block + src.slice(at));
  console.log(`✓ ${file}  ${(block.length / 1024).toFixed(0)} KB`);
  await page.close();
}
await browser.close();
server.close();
process.exit(failed ? 1 : 0);
